"""Short 'how it matches / how it doesn't' texts for the top-5 places and the three highlighted cards,
built only from our numbers (feature percentiles vs the target profile, S and rank) -> docs/data/explanations.json."""
import importlib
import json
from common import SITE_DATA

ae = importlib.import_module('04_analog_engine')
val = importlib.import_module('05_validation')
MATCH, DIFFER = 0.8, 0.5           # same thresholds as the website chips
PHRASE = dict(aridity='drier', barren='fewer plants', thermal_range='a larger day–night temperature swing', cold='colder nights',
              dust='dustier air', roughness='rougher terrain', elevation='higher ground')


def top_fmt(position, n):
    x = position / n * 100
    return f'{x:.1f}' if x >= 0.1 else f'{x:.3f}'


def explain(name, vec, profile, S, position, n, cannot):
    s = {f: 1 - abs(vec[f] - profile[f]) for f in ae.FEATURES}
    match = [f for f in ae.FEATURES if s[f] >= MATCH]
    differ = [f for f in ae.FEATURES if s[f] < DIFFER]
    partly = [f for f in ae.FEATURES if DIFFER <= s[f] < MATCH]
    pct = lambda f: round(vec[f] * 100)
    yes = ('; '.join(f"{PHRASE[f]} than {pct(f)}% of Earth's land (target profile {profile[f]:.2f})" for f in match)
           or 'no single feature is a close match')
    no = []
    for f in differ:
        side = 'less' if vec[f] < profile[f] else 'more'
        no.append(f"{FEAT[f]}: percentile {vec[f]:.2f} vs target {profile[f]:.2f} ({side} extreme than the target)")
    part = '; '.join(f"{FEAT[f]} (percentile {vec[f]:.2f} vs target {profile[f]:.2f})" for f in partly)
    return dict(place=name, matches=f"Matches: {yes}." + (f" Partly: {part}." if part else '')
                + f" Overall S = {S:.2f}, rank #{position:,} of {n:,} land cells (top {top_fmt(position, n)}% of land cells).",
                differs=('Differs: ' + '; '.join(no) + '.' if no else 'Differs: no feature is far from the target profile.')
                        + f" Earth cannot reproduce: {', '.join(cannot)}.",
                features={f: round(vec[f], 3) for f in ae.FEATURES}, profile=profile, position=position, n_cells=n, top_percent=round(position / n * 100, 3), S=round(S, 3),
                match_features=match, partly_features=partly, differ_features=differ)


FEAT = dict(aridity='dryness', barren='lack of plants', thermal_range='day–night swing', cold='cold', dust='dust',
            roughness='terrain roughness', elevation='elevation')


def main():
    lon, lat, P = val.load_grid()
    T = json.loads((SITE_DATA / 'targets.json').read_text())
    sc = json.loads((SITE_DATA / 'showcase.json').read_text(encoding='utf-8'))
    w = T['modes'][sc['mode']]['weights']
    out = dict(demo=False, label='AI-written from our data',
               method='Generated by pipeline/13_explanations.py from feature percentiles (analog_grid), target profiles '
                      f'(targets.json), S and rank (showcase.json). Match = s_i >= {MATCH}, differs = s_i < {DIFFER}.',
               top={}, cards={})
    for tk, rows in sc['top'].items():
        prof, cannot = T['targets'][tk]['profile'], T['targets'][tk]['cannot']
        S_all = ae.similarity(P, prof, w)
        out['top'][tk] = []
        for r in rows:
            i = ae.cell_index(lon, lat, r['lon'], r['lat'])
            vec = dict(zip(ae.FEATURES, map(float, P[i])))
            out['top'][tk].append(explain(r['region'], vec, prof, r['S'], int((S_all > S_all[i]).sum()) + 1, len(S_all), cannot))
    for c in sc['cards']:
        prof, cannot = T['targets'][c['target']]['profile'], T['targets'][c['target']]['cannot']
        out['cards'][c['key']] = [explain(r['place'], r['features'], prof, r['S'], r['position'], sc['n_cells'], cannot) for r in c['rows']]
    (SITE_DATA / 'explanations.json').write_text(json.dumps(out, indent=1, ensure_ascii=False), encoding='utf-8')
    print(json.dumps(out['cards']['mangystau'], indent=1, ensure_ascii=False))
    print(out['top']['moon_south_pole'][0])


if __name__ == '__main__':
    main()
